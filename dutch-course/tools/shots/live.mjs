import { chromium } from 'playwright';
const URL0 = process.argv[2] || 'https://ipantelidis.github.io/fable5-projects/dutch-course/';
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 390, height: 844 } }); const p = await ctx.newPage();
const errs = []; p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
const failed = []; p.on('requestfailed', (r) => failed.push(r.url().split('/').slice(-2).join('/')));
const t0 = Date.now(); await p.goto(URL0, { waitUntil: 'load' }); console.log('load ms', Date.now() - t0);
await p.waitForTimeout(1500);
const sw = await p.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); await navigator.serviceWorker.ready; return r ? (r.active ? 'active' : 'installing') : 'none'; });
console.log('service worker:', sw);
const man = await p.evaluate(async () => { const l = document.querySelector('link[rel=manifest]'); const r = await fetch(l.href); const j = await r.json(); return r.status + ' ' + j.name + ' icons=' + j.icons.length + ' start=' + j.start_url; });
console.log('manifest:', man);
await p.waitForTimeout(2500);
const cached = await p.evaluate(async () => { const ks = await caches.keys(); let n = 0; for (const k of ks) n += (await (await caches.open(k)).keys()).length; return ks.join(',') + ' files=' + n; });
console.log('cache:', cached);
await ctx.setOffline(true);
await p.reload(); await p.waitForTimeout(800);
console.log('offline reload title:', await p.title(), '| home rendered:', await p.evaluate(() => !!document.querySelector('.hero')));
await p.evaluate(() => { location.hash = '#/lesson/s2u1l1'; }); await p.waitForTimeout(500);
console.log('offline lesson rendered:', await p.evaluate(() => document.querySelector('#view h1') && document.querySelector('#view h1').textContent));
console.log('errors:', errs.join(' | ') || 'none', '| failed requests:', failed.join(', ') || 'none');
await b.close();
